"""Turn the repaired PDF text (output of extract_pdf.py) into src/lyrics.js.

Usage: python tools/extract_pdf.py mummanikkovai.pdf > fixed.txt
       python tools/build_lyrics.py fixed.txt > src/lyrics.js

Only the ten pāsurams are kept: the recording doesn't recite the taniyan or the
closing "சீரார் தூப்புல் ..." line.

Timings are *estimates* spread over the 6:56 recording by syllable weight.
Use the widget's Sync mode to replace them with exact timings.
"""
import json, re, sys

DURATION = 416.0      # length of youtu.be/_S8ixInldNY in seconds
START, END = 2.0, 412.0
SKIP = re.compile(r'^(www\.prapatti\.com|\d+|Sunder Kidāmbi|ஶ்ரீ தேசிக ப்ரபந்தம்|மும்மணிக்கோவை)$')
FIXES = {'பாரொன்ற ச்சொன்ன': 'பாரொன்றச் சொன்ன', 'வானேற ப்போமளவும்': 'வானேறப் போமளவும்'}

raw = open(sys.argv[1], encoding='utf-8').read()
for a, b in FIXES.items():
    raw = raw.replace(a, b)
lines = [l.strip() for l in raw.splitlines()]
i = next(k for k, l in enumerate(lines) if l.startswith('சீரொன்று'))
end = next(k for k, l in enumerate(lines) if l.startswith('அடிவரவு'))

out, verse = [], 0
repeated = set()  # pāsurams whose first line starts with ‡ are chanted twice
for l in lines[i:end]:
    if not l or SKIP.match(l):
        continue
    m = re.search(r'॥\s*॥\s*(\d+)\s*॥\s*॥', l)
    text = re.sub(r'॥.*$', '', l)
    if l.startswith('‡'):
        repeated.add(verse)
    text = re.sub(r'[⋆‡₃]', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    if text:
        out.append({'v': verse, 'text': text})
    if m:  # "॥ n ॥" closes verse n; following lines belong to verse n+1
        verse = int(m.group(1)) + 1
    elif verse == 0 and text.startswith('வானேற'):
        verse = 1
out = [o for o in out if o['v'] != 0]  # drop the taniyan

# In the PDF, a pāsuram that starts with ‡ is repeated when chanted, so the recording
# says it twice in a row. Playback follows this order rather than the order of the text.
ORDER = [v for v in sorted({o['v'] for o in out}) for _ in range(2 if v in repeated else 1)]

# timeline = every line in the order it is recited: [line index, start time]
timeline = [k for v in ORDER for k, o in enumerate(out) if o['v'] == v]

# estimated timings by akshara weight
def weight(t):
    letters = len(re.findall(r'[\u0b85-\u0bb9]', t))
    return letters + 3.0
gaps = [0.0] + [2.5 if timeline[k] != timeline[k - 1] + 1 else 0 for k in range(1, len(timeline))]
w = [weight(out[i]['text']) + g for i, g in zip(timeline, gaps)]
scale = (END - START) / sum(w)
t = START
times = []
for wi, g in zip(w, gaps):
    t += g * scale
    times.append(round(t, 2))
    t += (wi - g) * scale

print('// Generated by tools/build_lyrics.py from prapatti.com\'s Mummanikkovai PDF.')
print('// lines: the text, v = pāsuram number.')
print('// order: pāsurams in the order the recording recites them (those marked ‡ in the PDF are said twice).')
print('// timeline: every recited line in playback order as [index into lines, start time in seconds].')
print('//           Start times are estimates; Sync mode in the widget replaces them with exact ones.')
print('window.LYRICS = {')
print('  title: "மும்மணிக்கோவை", subtitle: "Swami Desikan · Sri Desika Prabandham",')
print('  videoId: "_S8ixInldNY", duration: %d,' % DURATION)
print('  order: %s,' % json.dumps(ORDER))
print('  lines: [')
for o in out:
    print('    ' + json.dumps({'v': o['v'], 'text': o['text']}, ensure_ascii=False) + ',')
print('  ],')
print('  timeline: [')
for k in range(0, len(timeline), 6):
    print('    ' + ', '.join('[%d, %s]' % (i, tt) for i, tt in zip(timeline[k:k + 6], times[k:k + 6])) + ',')
print('  ],')
print('};')
