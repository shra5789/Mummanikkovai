"""Build src/texts/dayasatakam.js from prapatti.com's romanised Dayāśatakam PDF.

The Devanagari PDF on prapatti.com uses a broken font encoding, so its text can't be
extracted. The romanised (ISO 15919) edition extracts cleanly, so it is converted to
Devanagari here with `indic-transliteration` (pip install indic-transliteration pymupdf).

Usage: python tools/build_dayasatakam.py dayaashatakam_english.pdf > src/texts/dayasatakam.js
       (https://www.prapatti.com/slokas/english/desika-stotramaala/dayaashatakam.pdf)
"""
import json, re, sys, unicodedata
import pymupdf
from indic_transliteration import sanscript

# ---- extract PDF lines, inserting spaces where the PDF only leaves a gap between glyphs
lines = []
for page in pymupdf.open(sys.argv[1]):
    for b in page.get_text('rawdict')['blocks']:
        for l in b.get('lines', []):
            out, prev = '', None
            for c in (c for s in l['spans'] for c in s['chars']):
                if prev is not None and c['bbox'][0] - prev['bbox'][2] > 1.5 and c['c'] != ' ' and not out.endswith(' '):
                    out += ' '
                out += c['c']; prev = c
            lines.append(re.sub(r'Á\s+Á', 'ÁÁ', re.sub(r'\s+', ' ', out)).strip())

SKIP = re.compile(r'^(www\.prapatti\.com|\d+|Sunder Kidāmbi|śrīdēśikastōtrāṇi|śrīdayāśatakam|śrīḥ|śrīmatē .*namaḥ)$')
start = next(k for k, l in enumerate(lines) if l.startswith('śrīmān vēṅkaṭanāthāryaḥ'))
body = [l for l in lines[start:] if l and not SKIP.match(l)]

# ---- group into display lines. Each PDF line is normally one line of the ślōka; in long metres
# (e.g. ślōka 107) the PDF splits every pāda over two lines, so those are paired back up.
END = re.compile(r'(ÁÁ\s*(\d+)\s*ÁÁ|ÁÁ)\s*$')
units, verse, group = [], 0, []

def flush(group, verse):
    if len(group) == 8:
        group = [group[k] + ' ' + group[k + 1] for k in range(0, 8, 2)]
    for raw in group:
        end = '॥' if END.search(raw) else ('।' if raw.endswith('Á') else '')
        text = re.sub(r'(ÁÁ\s*\d+\s*ÁÁ|ÁÁ|Á)\s*$', '', raw).strip()
        text = re.sub(r'\s*-\s+', '', text)  # word broken across PDF lines: "vyatiṣajat - svargā…"
        text = re.sub(r'\s*-$', '-', text)    # compound running on into the next line
        units.append({'v': verse, 'text': text, 'end': end})

for l in body:
    if l.startswith('ÁÁ iti'):           # "iti śrīdayāśatakaṃ samāptam" — not recited
        verse = 109                        # what follows is the closing taniyan
        continue
    group.append(l)
    m = END.search(l)
    if m:
        flush(group, verse); group = []
        verse = int(m.group(2)) + 1 if m.group(2) else (1 if verse == 0 else verse)
if group:
    flush(group, verse)

def dev(t):
    t = unicodedata.normalize('NFC', t)
    for a, b in [('ṃ', 'ṁ'), ('ṛ', 'r̥'), ('ṝ', 'r̥̄'), ('ḻ', 'ḷ'), ('’', "'")]:
        t = t.replace(a, b)
    return sanscript.transliterate(t, sanscript.ISO, sanscript.DEVANAGARI)

out = [{'v': u['v'], 'text': (dev(u['text']) + (' ' + u['end'] if u['end'] else '')).strip()} for u in units]

# Sanskrit Dēśika stōtras: the first and last ślōkas are chanted twice.
verses = sorted({o['v'] for o in out if 1 <= o['v'] <= 108})
first, last = verses[0], verses[-1]
order = [0] + [v for v in verses for _ in range(2 if v in (first, last) else 1)] + [109]

print('// Generated by tools/build_dayasatakam.py from prapatti.com\'s Dayāśatakam (romanised edition,')
print('// converted to Devanagari). v = ślōka number; 0 = opening taniyan, 109 = closing taniyan.')
print('// order: ślōkas in the order they are chanted (the first and last are said twice).')
print('window.SLOKAM_TEXTS = window.SLOKAM_TEXTS || {};')
print('window.SLOKAM_TEXTS.dayasatakam = {')
print('  verseWord: "श्लोकः", verseCount: %d, labels: { 0: "तनियन्", 109: "तनियन्" },' % len(verses))
print('  order: %s,' % json.dumps(order))
print('  lines: [')
for o in out:
    print('    ' + json.dumps(o, ensure_ascii=False) + ',')
print('  ],')
print('};')
